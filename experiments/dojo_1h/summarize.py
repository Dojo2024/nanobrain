"""Summarize every run under the output dir as markdown tables, one row per arm (mean over seeds).

  FOMO      last layer (<run>/eval/) and each layer readout (<run>/readout/<name>/), headline metric per task
  brainmarks <run>/brainmarks*/ (11 tasks; ADHD fails upstream), with the mean rank of the arm when it is
            added alone to the 5 reference models (our values rounded to 2 dp like the reference table)

A cell with fewer seeds than the arm shows the count, e.g. .801(2). Missing cells are "-".
Variants that only ran the 7 whole-scan tasks (`brainmarks-brainpool`, `brainmarks-cat9-12`) copy their
segmentation cells from the same seeds' plain `brainmarks/` run, marked "p", so the rank stays over 11 tasks.

usage: python experiments/dojo_1h/summarize.py /data/dojo/nanobrain/output > experiments/dojo_1h/all_results.md
"""

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

from nanobrain.eval.tasks import DEFAULT_TASKS, HEADLINE_METRICS

FOMO_SHORT = ["lesion", "tumor", "age", "hippo", "nerve", "vessel", "pmg", "cortex"]
BM_TASKS = ["abide_diagnosis", "cnp_diagnosis", "ucsf_idh", "upenn_survival_1y", "soop_mrs_poor", "ixi_age",
            "openbhb_age", "brats_whole_tumor", "brats_tumor_core", "brats_enhancing_tumor", "soop_lesion"]
BM_SHORT = ["ABIDE", "CNP", "IDH", "UPENN", "mRS", "IXI", "BHB", "WT", "TC", "ET", "lesion"]
BM_SEG = BM_TASKS[7:]
BM_METRIC = {"segmentation": "dice", "classification": "auroc", "regression": "r2"}
# the user's reference table (300 samples per split, ADHD dropped), in BM_TASKS order
REFS = {
    "Neuro-JEPA": [.63, .68, .94, .74, .72, .87, .88, .75, .59, .43, .35],
    "NeuroVFM": [.59, .70, .94, .72, .73, .92, .84, .69, .58, .44, .38],
    "BrainDINO": [.61, .71, .93, .71, .71, .80, .79, .75, .64, .45, .32],
    "DINOv3": [.61, .62, .92, .74, .77, .79, .74, .73, .59, .43, .30],
    "BrainIAC": [.52, .55, .76, .65, .71, .58, .47, .74, .31, .32, .37],
}
SKIP = {"patchsize-smoke"}


def load(path, key):
    try:
        return json.load(open(path))[key] if key else json.load(open(path))
    except FileNotFoundError:
        return None


def bm_score(path):
    d = load(path, None)
    return None if d is None else d["metrics"][BM_METRIC[d["type"]]]


def find_runs(out):
    # run dir = parent of eval/ or brainmarks*/; arm = run dir without its s<seed> suffix
    runs = defaultdict(dict)
    for sub in sorted(out.rglob("*")):
        if not sub.is_dir() or not (sub.name == "eval" or sub.name.startswith("brainmarks")):
            continue
        run = sub.parent
        if "readout" in run.parts or run.relative_to(out).parts[0] in SKIP:
            continue
        seed = run.name if re.fullmatch(r"s\d+", run.name) else "-"
        arm = str((run.parent if seed != "-" else run).relative_to(out))
        runs[arm][seed] = run
    return runs


def epochs(run):
    try:
        return json.loads(open(run / "log.json").read().splitlines()[-1])["epoch"] + 1
    except (FileNotFoundError, IndexError):
        return None


def cell(vals, n):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "-"
    s = re.sub(r"^(-?)0\.", r"\1.", f"{np.mean(vals):.3f}")
    return s if len(vals) == n else f"{s}({len(vals)})"


def mean_rank(ours):
    # rank of our model among the 5 refs + ours on each task we have; ties share the average rank
    ranks = []
    for i, v in enumerate(ours):
        if v is None:
            continue
        vals = [r[i] for r in REFS.values()] + [round(v, 2)]
        ranks.append(sum(x > vals[-1] for x in vals) + (sum(x == vals[-1] for x in vals) + 1) / 2)
    return np.mean(ranks), len(ranks)


def main(out):
    runs = find_runs(out)
    print(f"Generated by `experiments/dojo_1h/summarize.py {out}`. Mean over seeds; `(k)` = only k seeds.\n")

    print("## FOMO, last layer\n")
    print("| arm | seeds | epochs | " + " | ".join(FOMO_SHORT) + " |")
    print("|---|---|---|" + "---|" * len(FOMO_SHORT))
    for arm, seeds in sorted(runs.items()):
        have = {s: r for s, r in seeds.items() if (r / "eval").is_dir()}
        if not have:
            continue
        ep = [e for e in map(epochs, have.values()) if e]
        cells = [cell([load(r / "eval" / f"{t}.json", HEADLINE_METRICS[t]) for r in have.values()], len(have))
                 for t in DEFAULT_TASKS]
        print(f"| {arm} | {','.join(have)} | {np.mean(ep):.0f} | " + " | ".join(cells) + " |" if ep else
              f"| {arm} | {','.join(have)} | - | " + " | ".join(cells) + " |")

    print("\n## FOMO, layer readouts\n")
    print("| arm | readout | seeds | " + " | ".join(FOMO_SHORT) + " |")
    print("|---|---|---|" + "---|" * len(FOMO_SHORT))
    for arm, seeds in sorted(runs.items()):
        names = sorted({p.name for r in seeds.values() for p in (r / "readout").glob("*") if p.is_dir()})
        for name in names:
            have = {s: r / "readout" / name for s, r in seeds.items() if (r / "readout" / name).is_dir()}
            cells = [cell([load(r / f"{t}.json", HEADLINE_METRICS[t]) for r in have.values()], len(have))
                     for t in DEFAULT_TASKS]
            print(f"| {arm} | {name} | {','.join(have)} | " + " | ".join(cells) + " |")

    print("\n## brainmarks-smri vs the 5 reference models\n")
    print("Rank = mean rank over the tasks present when the arm is added alone to the 5 references "
          "(1 = best of 6). References ranked among themselves (11 tasks): see the reference rows.\n")
    print("| arm | readout | seeds | rank (tasks) | " + " | ".join(BM_SHORT) + " |")
    print("|---|---|---|---|" + "---|" * len(BM_SHORT))
    for name, vals in REFS.items():
        print(f"| *{name}* | ref | - | - | " + " | ".join(f"{v:.2f}".lstrip("0") for v in vals) + " |")
    for arm, seeds in sorted(runs.items()):
        variants = sorted({p.name for r in seeds.values() for p in r.glob("brainmarks*")
                           if p.is_dir() and "smoke" not in p.name})
        for var in variants:
            have = {s: r for s, r in seeds.items() if (r / var).is_dir()}
            cols, means, marks = [], [], []
            for t in BM_TASKS:
                src = var
                if t in BM_SEG and not any((r / var / f"{t}.json").exists() for r in have.values()):
                    src = "brainmarks"
                v = [bm_score(r / src / f"{t}.json") for r in have.values()]
                c = cell(v, len(have))
                cols.append(c + ("p" if src != var and c != "-" else ""))
                v = [x for x in v if x is not None]
                means.append(np.mean(v) if v else None)
            rank, n = mean_rank(means)
            label = var.removeprefix("brainmarks").removeprefix("-") or "plain"
            print(f"| {arm} | {label} | {','.join(have)} | {rank:.2f} ({n}) | " + " | ".join(cols) + " |")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
