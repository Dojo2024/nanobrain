"""Pick per-axis winners from the finished iso-flop sweep and emit the combination
and ablation configs (winner + the predictions/visible-patch settings), ready to
launch. Nothing here submits anything.

Per-axis winners: best 2-seed mean open score among each axis's candidates
(width, depth, mlp ratio, head count) vs the base (768/12/4/12) anchor. The
combination arm stacks every axis whose winner beat base; the ablation arms
remove one winning axis at a time. Every emitted config keeps the winning
total_steps (iso-flop); the ramp variants (rampdn 1920->640, rampup 640->1920)
re-use the winner's budget with the visible ramp on.

Usage: uv run python scripts/combine_winners.py
"""

import copy
import json
from pathlib import Path

from omegaconf import OmegaConf

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "output" / "iso"
CFG = ROOT / "configs" / "iso"
BASE = "base-e768-d12"

# axis -> (configs in the axis, the config field the axis varies)
AXES = {
    "width": ["wide-e640-d16-h10", "wide-e896-d10-h14", "wide-e1024-d8-h16", "wide-e1152-d6-h12", "narrow-e640-d12"],
    "depth": ["deep-e768-d16", "shallow-e768-d8"],
    "mlp": ["mlp6-e768-d10", "mlp6-e896-d8"],
    "heads": ["heads8-e768-d12", "heads16-e768-d12"],
}


def load():
    runs = {}
    for agg in sorted(OUT.glob("*/s*/eval/aggregate.json")):
        run_dir = agg.parent.parent
        try:
            score = json.loads(agg.read_text())["summary"]["open"]["score"]
            summary = json.loads((run_dir / "summary.json").read_text())
            flops = summary.get("train_flops")
        except Exception:
            continue
        if not flops or flops < 5e17:  # incomplete budget runs don't vote
            continue
        runs.setdefault(run_dir.parent.name, {})[run_dir.name] = (score, flops)
    return runs


def winner_of(runs, names, base_score):
    scored = []
    for n in names:
        seeds = runs.get(n)
        if not seeds or len(seeds) < 2:
            continue
        m = sum(v["open"] for v in seeds.values()) / len(seeds)
        scored.append((m, n))
    if not scored:
        return None
    m, name = max(scored)
    return (m, name) if m > base_score else None


def main():
    runs = load()
    if BASE not in runs or len(runs.get(BASE, {})) < 2:
        print("base run incomplete - wait for the sweep")
        return
    base = sum(v["open"] for v in runs[BASE].values()) / 2

    print(f"{'config':24s} {'mean':>8s} {'vs base':>9s}")
    winners = {}
    for axis, names in AXES.items():
        w = winner_of(runs, names, base)
        for n in names:
            seeds = runs.get(n, {})
            if len(seeds) < 2:
                continue
            m = sum(v["open"] for v in seeds.values()) / len(seeds)
            print(f"{n:24s} {m:8.4f} {m - base:+9.4f}   ({axis})")
        if w:
            winners[axis] = w
            print(f"  -> {axis} winner: {w[1]} ({w[0]:.4f})\n")

    if not winners:
        print("\nbase wins every axis - combine stage: base +/- the visible-ramp only")
        combo_cfg = OmegaConf.load(CFG / f"{BASE}.yaml")
    else:
        print(f"\ncombining: {[f'{a}:{w[1]}' for a, w in winners.items()]}")
        combo_cfg = OmegaConf.load(CFG / f"{list(winners.values())[0][1]}.yaml")
        for axis, (m, name) in list(winners.items())[1:]:
            wcfg = OmegaConf.load(CFG / f"{name}.yaml")
            for key in ("depth", "embed_dim", "num_heads", "mlp_ratio"):
                if key in wcfg.model_kwargs:
                    combo_cfg.model_kwargs[key] = wcfg.model_kwargs[key]

    outdir = ROOT / "configs" / "combine"
    outdir.mkdir(parents=True, exist_ok=True)
    combos = []
    for tag, ramp in [("noramp", None), ("rampdn", (1920, 640)), ("rampup", (640, 1920))]:
        cfg = copy.deepcopy(combo_cfg)
        cfg["name"] = f"{combo_cfg.get('name', 'combo')}-{tag}"
        if ramp:
            cfg["visible_ramp_start"], cfg["visible_ramp_end"] = ramp
        else:
            cfg["visible_ramp_start"] = None
            cfg["visible_ramp_end"] = None
        OmegaConf.save(cfg, outdir / f"{cfg['name']}.yaml")
        combos.append(cfg["name"])

    with (ROOT / "scripts" / "next_combine.sbatch.sh").open("w") as f:
        f.write("#! generated by combine_winners.py - review, then run manually\n")
        f.write("#! usage: sbatch scripts/sweep_run.sbatch combine/<name> <seed>\n")
        for name in combos:
            for seed in ("7338", "1", "2", "3"):
                f.write(f"sbatch scripts/sweep_run.sbatch combine/{name} {seed}\n")
    print(f"wrote configs/combine/: {combos}")
    print("wrote scripts/next_combine.sbatch.sh - NOT submitted")


if __name__ == "__main__":
    main()
